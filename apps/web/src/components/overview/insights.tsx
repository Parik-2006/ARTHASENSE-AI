import { IndicatorLink } from "@/components/guide/indicator-link";
import { HelpTip } from "@/components/guide/help-tip";
import { ClassBadge } from "@/components/source/source-attribution";
import { formatPeriod } from "@/lib/indicator";
import type { IndicatorBundle } from "@/lib/overview-data";
import { buildInsights } from "@/lib/overview-insights";

export function InsightsSection({ bundles }: { bundles: IndicatorBundle[] }) {
  const items = bundles.flatMap((b) => buildInsights(b).map((i) => ({ i, b })));
  return (
    <section id="insights" aria-labelledby="insights-h" className="mt-10 scroll-mt-20">
      <h2 id="insights-h" className="font-serif text-2xl font-semibold tracking-tight">
        What do these numbers tell us?<HelpTip id="insight" />
      </h2>
      <p className="mt-1 max-w-3xl text-sm text-ink-muted">
        Statements generated by fixed rules from stored observations. They describe what the data shows; they do not explain causes or predict the future.
      </p>
      {items.length === 0 ? (
        <p role="status" className="mt-4 rounded-md border border-dashed border-rule px-4 py-8 text-center text-sm text-ink-muted">
          No insights can be produced because no observations are available.
        </p>
      ) : (
        <ul className="mt-4 grid gap-4 md:grid-cols-2 xl:grid-cols-3">
          {items.map(({ i, b }) => (
            <li key={i.id} className="flex flex-col rounded-md border border-rule bg-surface p-4">
              <div className="flex flex-wrap items-center gap-2 text-xs">
                <span className="rounded border border-rule px-1.5 py-0.5 font-medium">{b.shortName}</span>
                <ClassBadge cls={i.cls} />
                {i.period && <span className="text-ink-muted">{formatPeriod(i.period, true)}</span>}
              </div>
              <h3 className="mt-2 text-sm font-semibold">{i.headline}</h3>
              <p className="mt-1 text-sm text-ink-muted">{i.text}</p>
              <p className="figure mt-2 text-xs">{i.evidence}</p>
              <p className="mt-2 text-xs text-ink-muted">Source: {b.source.short} observations{i.cls === "calculated" ? " · calculated by ArthaSense" : ""}</p>
              <details className="mt-1 text-xs">
                <summary className="cursor-pointer text-accent underline focus-visible:outline-2 focus-visible:outline-accent">How was this calculated?</summary>
                <p className="mt-1 text-ink-muted">{i.method}</p>
              </details>
              <IndicatorLink path={b.path} className="mt-2 text-xs font-medium text-accent underline">
                Open {b.shortName} Intelligence →
              </IndicatorLink>
            </li>
          ))}
        </ul>
      )}
    </section>
  );
}
