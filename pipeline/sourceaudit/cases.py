def g(id_, group, title, url, params=None, **kw) -> Case:
    return Case(
        id=id_,
        group=group,
        title=title,
        source=kw.pop("source", API),
        op="GET",
        url=url,
        params=params or {},
        **kw,
    )


def m(id_, group, title, method, tool="", arguments=None, **kw) -> Case:
    args = {"tool": tool, "arguments": arguments or {}} if tool else {}
    return Case(
        id=id_,
        group=group,
        title=title,
        source=MCP,
        op="MCP",
        url=MCP_URL,
        mcp_method=method,
        mcp_args=args,
        **kw,
    )


