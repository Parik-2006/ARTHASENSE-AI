const API_DOWN = "Unable to load forecasts. Please check the API connection.";

interface Loaded {
  id: IndicatorId;
  info: SeriesInfo | null;
  run: Run | null;
  rows: ForecastRow[];
  models: string[];
  error: string | null;
}

async function loadForecast(id: IndicatorId, info: SeriesInfo | null): Promise<Loaded> {
  if (!info || info.future_forecasts === 0) return { id, info, run: null, rows: [], models: [], error: null };
  const runs = await getRuns(`?indicator=${id}&kind=forecast&status=completed&limit=30`);
  if (!runs.ok || runs.data.items.length === 0) {
    return { id, info, run: null, rows: [], models: [], error: runs.ok ? null : API_DOWN };
  }
  const run = runs.data.items[0]; // API orders by created_at, newest first. This is "most recent", not "best".
  const rows = await getRunForecasts(run.id);
  return {
    id,
    info,
    run,
    rows: rows.ok ? rows.data.items : [],
    models: [...new Set(runs.data.items.map((r) => r.model_name))],
    error: rows.ok ? null : API_DOWN,
  };
}

function unavailableText(l: Loaded): string {
  if (!l.info) return "Forecast status is not available from the API.";
  if (l.info.forecast_status === "no_data") return "No observations are stored, so no forecast can exist.";
  if (l.info.forecast_status === "insufficient_history") {
    return `${l.info.reason ?? "There is not enough history to evaluate a forecast."} ArthaSense does not show a forecast it cannot evaluate.`;
  }
  return l.info.reason ?? "No stored forecast exists for this indicator yet. Forecasts are computed offline and are never generated by this page.";
}

export async function ForecastSection({ bundles }: { bundles: IndicatorBundle[] }) {
  const [series, models] = await Promise.all([getForecastSeries(), getForecastModels()]);
  const loaded = series.ok
    ? await Promise.all(INDICATOR_IDS.map((id) => loadForecast(id, series.data.find((s) => s.indicator === id) ?? null)))
    : [];
  const unavailable = models.ok ? models.data.filter((m) => m.status === "unavailable") : [];

  return (
    <section id="forecast" data-tour="forecast" aria-labelledby="forecast-h" className="mt-10 scroll-mt-20">
      <h2 id="forecast-h" className="font-serif text-2xl font-semibold tracking-tight">
        What might happen next?<HelpTip id="forecast" />
      </h2>
      <p className="mt-1 max-w-3xl text-sm text-ink-muted">
        Model-generated forecasts read from stored runs. They are not official statistics and not predictions we stand behind: always read the uncertainty band. This page never trains a model.
      </p>
      {!series.ok ? (
        <p role="alert" className="mt-4 rounded-md border border-rule bg-surface px-4 py-6 text-sm text-up">{API_DOWN}</p>
      ) : (
        <div className="mt-4 grid gap-4 lg:grid-cols-3">
          {loaded.map((l) => {
            const b = bundles.find((x) => x.key === l.id)!;
            const history = (b.segments[0] ? derive(b.segments[0].observations) : [])
              .filter((r) => r.index !== null)
              .slice(-24)
              .map((r) => ({ period: r.period, index: r.index as number }));
            return (
              <article key={l.id} aria-label={`${b.shortName} forecast`} className="flex min-w-0 flex-col rounded-md border border-rule bg-surface p-4">
                <h3 className="text-sm font-semibold">{INDICATOR_NAMES[l.id]}</h3>
                {!l.run ? (
                  <p role="status" className="mt-3 text-sm text-ink-muted">
                    {l.error ?? unavailableText(l)}
                  </p>
                ) : (
                  <>
                    <p className="mt-2 flex flex-wrap items-center gap-2 text-xs">
                      <ClassBadge cls="forecast" />
                      <span>{l.run.model_name}</span>
                    </p>
                    <dl className="mt-2 grid grid-cols-2 gap-x-3 gap-y-1 text-xs">
                      <dt className="text-ink-muted">Forecast origin</dt>
                      <dd>{l.rows[0]?.origin_date ? monthLabel(l.rows[0].origin_date, true) : monthLabel(l.run.training_cutoff, true)}</dd>
                      <dt className="text-ink-muted">Horizon</dt>
                      <dd>{l.run.horizon} month{l.run.horizon === 1 ? "" : "s"} ahead</dd>
                      <dt className="text-ink-muted">Stored run</dt>
                      <dd>#{l.run.id} · {formatTimestamp(l.run.created_at)}</dd>
                      <dt className="text-ink-muted">Status</dt>
                      <dd>{l.run.status}</dd>
                    </dl>
                    {l.rows.length > 0 && history.length >= 2 && (
                      <div className="mt-3">
                        <ForecastChart history={history} forecast={l.rows} axisLabel={`${b.shortName} index`} name={`${b.shortName} index`} />
                      </div>
                    )}
                    {l.rows.length > 0 && (
                      <table className="mt-2 w-full text-left text-xs">
                        <caption className="sr-only">Stored forecast values for {b.shortName}</caption>
                        <thead className="text-ink-muted">
                          <tr><th scope="col" className="py-1 font-medium">Month</th><th scope="col" className="font-medium">Forecast</th><th scope="col" className="font-medium">80% range<HelpTip id="interval" /></th></tr>
                        </thead>
                        <tbody>
                          {l.rows.slice(0, 6).map((r) => (
                            <tr key={r.target_date} className="border-t border-rule">
                              <th scope="row" className="py-1 font-normal">{monthLabel(r.target_date)}</th>
                              <td className="figure">{fmt(r.forecast)}</td>
                              <td className="figure">{r.lower_80 !== null && r.upper_80 !== null ? `${fmt(r.lower_80)} – ${fmt(r.upper_80)}` : "none stored"}</td>
                            </tr>
                          ))}
                        </tbody>
                      </table>
                    )}
                    {l.models.length > 1 && (
                      <p className="mt-2 text-xs text-ink-muted">
                        Shown: the most recently stored run, not a recommendation. Other models with stored forecasts: {l.models.filter((m) => m !== l.run!.model_name).join(", ")}.
                      </p>
                    )}
                    <SourceAttribution
                      className="mt-3"
                      cls="forecast"
                      sources={[b.source]}
                      period={`origin ${l.rows[0]?.origin_date ? monthLabel(l.rows[0].origin_date) : monthLabel(l.run.training_cutoff)} · ${l.run.horizon}-month horizon`}
                      units="Index points"
                      retrievedAt={l.run.created_at}
                      method={`${l.run.model_name}, stored run #${l.run.id}. Input data: ${b.source.short} observations (base ${b.source.baseYear ?? "unknown"}). Prediction intervals as stored by the model run.`}
                    />
                  </>
                )}
                <Link href={`/forecasting/${l.id}`} className="mt-3 inline-block text-sm font-medium text-accent underline">
                  {b.shortName} forecasting details →
                </Link>
              </article>
            );
          })}
        </div>
      )}
      {unavailable.length > 0 && (
        <p className="mt-3 text-xs text-ink-muted">
          Not running in this deployment: {unavailable.map((m) => `${m.name}${m.unavailable_reason ? ` (${m.unavailable_reason})` : ""}`).join("; ")}. Their results are never shown.
        </p>
      )}
    </section>
  );
}

// ---------- reliability ----------

interface Rel {
  id: IndicatorId;
  rows: Run[];
  horizon: number | null;
  error: string | null;
  reason: string | null;
}

async function loadReliability(id: IndicatorId, info: SeriesInfo | null): Promise<Rel> {
  if (!info || info.completed_backtests === 0) {
    return { id, rows: [], horizon: null, error: null, reason: info?.reason ?? "No completed backtests are stored." };
  }
  const res = await getRuns(`?indicator=${id}&kind=backtest&status=completed&limit=100`);
  if (!res.ok) return { id, rows: [], horizon: null, error: API_DOWN, reason: null };
  const usable = res.data.items.filter((r) => r.n_origins !== null && r.metrics.mae !== undefined);
  if (!usable.length) return { id, rows: [], horizon: null, error: null, reason: "Backtests exist but report no error metrics." };
  const horizon = Math.min(...usable.map((r) => r.horizon));
  const latestPerModel = new Map<string, Run>();
  for (const r of usable.filter((x) => x.horizon === horizon)) if (!latestPerModel.has(r.model)) latestPerModel.set(r.model, r); // newest first
  return { id, rows: [...latestPerModel.values()].sort((a, b) => a.model_name.localeCompare(b.model_name)), horizon, error: null, reason: null };
}

export async function ReliabilitySection({ bundles }: { bundles: IndicatorBundle[] }) {
  const series = await getForecastSeries();
  const rels = series.ok ? await Promise.all(INDICATOR_IDS.map((id) => loadReliability(id, series.data.find((s) => s.indicator === id) ?? null))) : [];
  return (
    <section id="reliability" data-tour="reliability" aria-labelledby="reliability-h" className="mt-10 scroll-mt-20">
      <h2 id="reliability-h" className="font-serif text-2xl font-semibold tracking-tight">
        How reliable have our forecasts been?<HelpTip id="metrics" />
      </h2>
      <p className="mt-1 max-w-3xl text-sm text-ink-muted">
        Backtesting replays each model on earlier months and measures its mistakes. MAE is the average size of those mistakes, in index points, so it can only be compared between models tested on the same indicator, horizon and months. Good backtests do not guarantee future accuracy.
      </p>
      {!series.ok ? (
        <p role="alert" className="mt-4 rounded-md border border-rule bg-surface px-4 py-6 text-sm text-up">{API_DOWN}</p>
      ) : (
        <div className="mt-4 grid gap-4 lg:grid-cols-3">
          {rels.map((r) => {
            const sameWindow = new Set(r.rows.map((x) => `${x.evaluation_start}|${x.evaluation_end}|${x.n_origins}`)).size <= 1;
            return (
              <article key={r.id} className="min-w-0 rounded-md border border-rule bg-surface p-4">
                <h3 className="text-sm font-semibold">{INDICATOR_NAMES[r.id]}</h3>
                {r.rows.length === 0 ? (
                  <p role="status" className="mt-3 text-sm text-ink-muted">{r.error ?? `Evaluation unavailable. ${r.reason ?? ""}`}</p>
                ) : (
                  <>
                    <p className="mt-1 text-xs text-ink-muted">{r.horizon}-month-ahead backtests, newest run per model, listed alphabetically (not ranked).</p>
                    <div className="mt-2 overflow-x-auto">
                      <table className="w-full text-left text-xs">
                        <caption className="sr-only">Backtest results for {r.id.toUpperCase()}</caption>
                        <thead className="text-ink-muted">
                          <tr>
                            <th scope="col" className="py-1 font-medium">Model</th>
                            <th scope="col" className="font-medium">Origins</th>
                            <th scope="col" className="font-medium">MAE</th>
                            <th scope="col" className="font-medium">80% cover</th>
                          </tr>
                        </thead>
                        <tbody>
                          {r.rows.map((x) => (
                            <tr key={x.id} className="border-t border-rule">
                              <th scope="row" className="py-1 font-normal">{x.model_name}</th>
                              <td className="figure">{x.n_origins}</td>
                              <td className="figure">{fmtMetric("mae", x.metrics.mae)}</td>
                              <td className="figure">{x.metrics.coverage_80 !== undefined ? fmtMetric("coverage_80", x.metrics.coverage_80) : "—"}</td>
                            </tr>
                          ))}
                        </tbody>
                      </table>
                    </div>
                    {!sameWindow && (
                      <p className="mt-2 rounded border border-warn px-2 py-1 text-xs text-warn">
                        These runs used different evaluation months or origin counts, so their errors are not directly comparable. The model comparison page checks this.
                      </p>
                    )}
                    {r.rows.some((x) => (x.n_origins ?? 0) < 12) && (
                      <p className="mt-2 text-xs text-warn">Some models have fewer than 12 backtest origins: treat their error figures as rough.</p>
                    )}
                    <p className="mt-2 text-xs text-ink-muted">
                      Plain reading: on average the model&apos;s {r.horizon}-month-ahead forecasts missed the actual {r.id.toUpperCase()} index by about the MAE shown, in index points, over the backtest months.
                    </p>
                    <SourceAttribution
                      className="mt-3"
                      cls="forecast"
                      sources={[bundles.find((x) => x.key === r.id)!.source]}
                      period={`${r.rows.length} model${r.rows.length === 1 ? "" : "s"} · ${r.horizon}-month horizon`}
                      units="Index points"
                      retrievedAt={r.rows[0].created_at}
                      method="Backtest metrics stored with each ArthaSense model run, computed against official observations. Evaluation is by ArthaSense, not by the data publisher."
                    />
                  </>
                )}
              </article>
            );
          })}
        </div>
      )}
      <p className="mt-3 text-sm">
        <Link href="/forecasting/comparison" className="text-accent underline">Detailed model comparison →</Link>{" · "}
        <Link href="/report-card" className="text-accent underline">Report Card →</Link>
      </p>
    </section>
  );
}
